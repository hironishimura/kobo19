## キーパッドの作り

数字と演算子のほかに、上の帯から `=` `%` `万` `prev` `sum` `#` `,` をワンタップで入れられます。

関数と単位は別のパネルにまとまっています。

- **iPhone** — 「数字・関数・単位」のタブで、キーパッド全体を切り替えます
- **iPad・Mac** — 数字のキーは常に出たままで、左のパネルを「関数」「単位」ボタンで開け閉めします

「単位」パネルには換算の `in` `→` と、お金・時間・温度・長さ・重さ・面積・体積・速さ・データ量・角度の単位がまとまっています。

数字のキーは**右端に固定**されているので、パネルを開け閉めしても位置が動きません。

## 名前を打つとき

iPhone・iPad では `ABC` でシステムキーボードに切り替わります（上に演算子の帯は残ります）。`123` でキーパッドに戻ります。

⌫ は押しっぱなしで連続削除できます。

## キーを並べ替える

キーを**長押し（0.6秒）**すると並べ替えモードに入ります。つまんだまま動かして、好きな場所に置けます。

- 帯の「空きを足す」で空きマスを作れます（空きも動かせます。✕ で消せます）
- 「もとに戻す」で最初の並びに戻ります

**並びは iCloud で同期されます。** 一度決めた並びが、すべての端末で同じになります。

## 元に戻す・やり直す

打ち間違えたら **⌘Z**（キーパッド上部の ↩︎）で戻せます。やり直すのは **⇧⌘Z**（↪︎）です。

続けて打った分は 0.9 秒でまとめて1回分になります。改行・貼り付け・行ロックの変化は区切りになるので、改行の前後どちらへも戻れます。

**行のロックも本文と組にして覚えています。** 消した行を戻すと、ロックも一緒に戻ります。

履歴はシートごとで、アプリを閉じるまで残ります。

## 設定

歯車から開きます。並びは上から次のとおりです。

| 項目 | 内容 |
|---|---|
| 表示 | 白 / 黒 / 自動、文字サイズ、答えの欄の幅、シートの並べ方 |
| テンキー | 大 / 中 / 小 |
| 計算 | 小数桁数、角度（度 / ラジアン） |
| 文字の色 | 数字・単位・名前などの色分け |
| 使い方 | アプリの中の説明、利用規約 |
| 言語 | 自動 / 日本語 / English |
| 全消去 | すべての内容を消す |

**言語の切り替えに再起動は要りません。** 押した瞬間に切り替わります。入力に使う言葉（`円` `万` `坪` `sum` `prev` など）は、英語表示のときも日本語のまま使えます。

表示の既定は**黒**です。
